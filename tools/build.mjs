import fs from 'node:fs';
import path from 'node:path';
const root = fs.realpathSync(process.cwd()), output = path.resolve(root, 'dist'), marker = '.tinderbox-diagnostic-build';
if (path.dirname(output) !== root || output === root) throw Error('Unsafe build destination');
if (fs.existsSync(output)) {
  if (fs.lstatSync(output).isSymbolicLink() || !fs.existsSync(path.join(output, marker))) throw Error('Refusing to replace an unowned dist directory');
  if (fs.realpathSync(output) !== output) throw Error('Unexpected resolved output path');
  fs.rmSync(output, {recursive: true});
}
fs.mkdirSync(output);
for (const directory of ['src', 'workbenches/simulation', 'vendor']) fs.cpSync(path.join(root, directory), path.join(output, directory), {recursive: true, dereference: false});
fs.writeFileSync(path.join(output, marker), 'Generated by Tinderbox tools/build.mjs\n');
fs.writeFileSync(path.join(output, 'index.html'), '<!doctype html><html lang="en"><meta charset="utf-8"><title>Tinderbox diagnostics</title><meta http-equiv="refresh" content="0;url=workbenches/simulation/"><a href="workbenches/simulation/">Tinderbox simulation diagnostic</a></html>\n');
console.log('Built labelled diagnostic in dist/; all runtime URLs are local.');
